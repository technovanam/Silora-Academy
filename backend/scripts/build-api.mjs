// ============================================================================
// Builds deploy/api: the backend packaged as Firebase Cloud Functions (2nd gen).
//   - "api"     – the whole Express app, served at https://<site>/api/** by a Hosting rewrite
//   - job*      – the scheduled jobs (Cloud Scheduler instead of node-cron)
// Runs as the functions predeploy hook in firebase.prod.json. Secrets live in Secret Manager
// (firebase functions:secrets:set …); only non-secret settings are written here.
// ============================================================================
import fs from "fs";
import path from "path";
import { execSync } from "child_process";
import { fileURLToPath } from "url";

const backend = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const out = path.resolve(backend, "../deploy/api");
const SITE = process.env.SILORA_SITE_URL || "https://silora-academy.web.app";
const REGION = "asia-south1";

fs.rmSync(path.join(out, "portal"), { recursive: true, force: true });
fs.mkdirSync(out, { recursive: true });
for (const f of ["server.js", "mailer.js"]) fs.copyFileSync(path.join(backend, f), path.join(out, f));
fs.cpSync(path.join(backend, "portal"), path.join(out, "portal"), { recursive: true });

const pkg = JSON.parse(fs.readFileSync(path.join(backend, "package.json"), "utf8"));
const deps = { ...pkg.dependencies, "firebase-functions": "^6.4.0" };
fs.writeFileSync(
  path.join(out, "package.json"),
  JSON.stringify({ name: "silora-api", private: true, type: "module", main: "index.js", engines: { node: "22" }, dependencies: deps }, null, 2)
);

// Non-secret production settings. Keys starting with FIREBASE_ are reserved by Cloud
// Functions, so they're passed as SILORA_* and mapped back in index.js.
const env = {
  USE_FIREBASE_EMULATORS: "false",
  SILORA_PROJECT_ID: "silora-academy",
  SILORA_DATABASE_ID: "default",
  SILORA_STORAGE_BUCKET: "silora-academy.firebasestorage.app",
  SILORA_WEB_API_KEY: readEnv("FIREBASE_WEB_API_KEY"),
  PORTAL_URL: SITE,
  API_PUBLIC_URL: SITE,
  APP_TIMEZONE: "Asia/Kolkata",
  SMTP_HOST: readEnv("SMTP_HOST"),
  SMTP_PORT: readEnv("SMTP_PORT"),
  SMTP_USER: readEnv("SMTP_USER"),
  MAIL_USER: readEnv("MAIL_USER"),
  MAIL_FROM: readEnv("MAIL_FROM"),
  // Requests through Firebase Hosting are capped at 32 MB
  MAX_MATERIAL_MB: "30",
  MAX_MESSAGE_FILE_MB: "25",
  MESSAGE_FILE_RETENTION_DAYS: "7",
  RECORDING_RETENTION_DAYS: "7",
  // LiveKit runs on its own server (not on Firebase); set its public wss:// URL here
  LIVEKIT_URL: process.env.SILORA_LIVEKIT_URL || readEnv("LIVEKIT_URL"),
  LIVEKIT_API_KEY: readEnv("LIVEKIT_API_KEY"),
  LIVEKIT_ROOM_PREFIX: readEnv("LIVEKIT_ROOM_PREFIX") || "silora-class",
  LIVEKIT_EGRESS_ENABLED: "false",
  LIVEKIT_AUTO_RECORD: "true",
  // Cloud Scheduler runs the jobs (see job* functions)
  ENABLE_JOBS: "false",
};
fs.writeFileSync(
  path.join(out, ".env.silora-academy"),
  Object.entries(env).filter(([, v]) => v !== "").map(([k, v]) => `${k}=${JSON.stringify(v)}`).join("\n") + "\n"
);

fs.writeFileSync(
  path.join(out, "index.js"),
  `// Generated by backend/scripts/build-api.mjs – edit that file, not this one.
import { onRequest } from "firebase-functions/v2/https";
import { onSchedule } from "firebase-functions/v2/scheduler";
import { setGlobalOptions } from "firebase-functions/v2";

const SECRETS = ["SERVICE_ACCOUNT_JSON", "SMTP_PASS", "FILE_TOKEN_SECRET", "LIVEKIT_API_SECRET"];
setGlobalOptions({ region: "${REGION}", secrets: SECRETS });

function mapEnv() {
  const e = process.env;
  e.FIREBASE_PROJECT_ID = e.SILORA_PROJECT_ID;
  e.FIRESTORE_DATABASE_ID = e.SILORA_DATABASE_ID;
  e.FIREBASE_STORAGE_BUCKET = e.SILORA_STORAGE_BUCKET;
  e.FIREBASE_WEB_API_KEY = e.SILORA_WEB_API_KEY;
}

// Load the app lazily so deploy-time discovery doesn't connect to anything
let appPromise;
const getApp = () => (appPromise ||= (mapEnv(), import("./server.js").then((m) => m.default)));

// Multipart uploads: the functions runtime has already read the body into req.rawBody,
// so hand that buffer to multer/busboy instead of the (finished) request stream.
function replayBody(req) {
  if (req.rawBody && /multipart\\//i.test(req.headers["content-type"] || "")) {
    req.pipe = (dest) => (dest.end(req.rawBody), dest);
    req.unpipe = () => req;
  }
}

// One instance: the class waiting room is kept in memory.
export const api = onRequest({ memory: "1GiB", cpu: 1, concurrency: 80, maxInstances: 1, minInstances: 0, timeoutSeconds: 300 }, async (req, res) => {
  replayBody(req);
  (await getApp())(req, res);
});

const job = (schedule, name) =>
  onSchedule({ schedule, timeZone: "Asia/Kolkata", memory: "512MiB", timeoutSeconds: 540, retryCount: 0 }, async () => {
    mapEnv();
    const { JOBS } = await import("./portal/services/jobs.js");
    await JOBS[name]();
  });

export const jobMinute = job("every 1 minutes", "minute");
export const jobRetry = job("every 5 minutes", "retry");
export const jobHourly = job("20 * * * *", "hourly");
export const jobNightly = job("0 2 * * *", "nightly");
export const jobAlerts = job("0 9 * * *", "alerts");
export const jobAttendance = job("0 10 * * 6", "attendance");
export const jobAttendanceSunday = job("0 18 * * 0", "attendance");
`
);

execSync("npm install --omit=dev --no-audit --no-fund --loglevel=error", { cwd: out, stdio: "inherit" });
console.log(`Built ${path.relative(process.cwd(), out)} for ${SITE}`);

function readEnv(key) {
  const file = path.join(backend, ".env");
  if (!fs.existsSync(file)) return "";
  const line = fs.readFileSync(file, "utf8").split(/\r?\n/).find((l) => l.startsWith(key + "="));
  return line ? line.slice(key.length + 1).trim().replace(/^"(.*)"$/, "$1") : "";
}
